package com.music.bitchord.shared.wear

/**
 * Data Layer contract for the lyrics-sync feature (phone <-> watch).
 *
 * Both apps MUST share the same applicationId ([APPLICATION_ID]) and the same signing
 * certificate, otherwise Google Play services will not route DataClient / MessageClient
 * traffic between them.
 *
 * Purely additive: nothing in [WearProtocol] is touched.
 */
object WearSyncPaths {

    const val APPLICATION_ID = "com.music.bitchord"

    // --- Paths requested in the spec -------------------------------------------------
    /** DataClient: the full [SyncedLyricsPayload] (gzip JSON stored as an Asset). */
    const val LYRICS_PAYLOAD = "/bitchord/lyrics/payload"

    /** MessageClient: discrete playback events (TRACK / PLAY / PAUSE / SEEK). */
    const val PLAYBACK_STATE = "/bitchord/playback/state"

    /** MessageClient: 5 s periodic position heartbeat while playing. */
    const val PLAYBACK_HEARTBEAT = "/bitchord/playback/heartbeat"

    // --- Additive paths (watch -> phone) ---------------------------------------------
    /** MessageClient: watch -> phone transport command, body = [PlaybackCommand.name]. */
    const val PLAYBACK_COMMAND = "/bitchord/playback/command"

    /**
     * MessageClient: watch -> phone. Body = trackId (UTF-8) to force a lyrics re-send, or empty
     * to simply ask for the current playback state (cold start / reconnect).
     */
    const val LYRICS_REQUEST = "/bitchord/lyrics/request"

    // --- DataMap keys for LYRICS_PAYLOAD ---------------------------------------------
    const val KEY_TRACK_ID = "trackId"
    const val KEY_HASH = "hash"
    const val KEY_ASSET = "lyricsAsset"
    const val KEY_UPDATED_AT = "updatedAt"

    /** Sent as `lyricsHash` when the phone resolved the track but found no synced lyrics. */
    const val NO_LYRICS_HASH = "none"

    // --- Timing ----------------------------------------------------------------------
    const val HEARTBEAT_INTERVAL_MS = 5_000L

    /** Drift above this snaps the watch clock; below it the watch interpolates. */
    const val DRIFT_SNAP_THRESHOLD_MS = 500L
}